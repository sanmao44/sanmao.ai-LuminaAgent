import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifestUrl = 'https://ai.cangyuansuanli.cn/docs-static/manifest.json';
const docsRoot = 'https://ai.cangyuansuanli.cn/docs-static/';
const outputPath = path.join(root, 'lib', 'cangyuan-video-model-catalog.generated.ts');

async function fetchJson(url) {
  const response = await fetch(url, { headers: { accept: 'application/json' } });
  if (!response.ok) throw new Error(`官方文档请求失败：${response.status} ${url}`);
  return response.json();
}

async function mapConcurrent(items, limit, mapper) {
  const result = new Array(items.length);
  let nextIndex = 0;
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (nextIndex < items.length) {
      const index = nextIndex;
      nextIndex += 1;
      result[index] = await mapper(items[index]);
    }
  }));
  return result;
}

const manifest = await fetchJson(manifestUrl);
if (manifest.schemaVersion !== 1 || !Array.isArray(manifest.entries)) {
  throw new Error('官方 manifest schema 不受支持，未更新本地目录。');
}

const entries = manifest.entries
  .filter((entry) => entry.kind === 'model' && entry.capability === 'video' && entry.status === 'current')
  .sort((left, right) => String(left.publicModel).localeCompare(String(right.publicModel)));
if (!entries.length || entries.some((entry) => typeof entry.publicModel !== 'string' || typeof entry.source !== 'string')) {
  throw new Error('官方 manifest 没有有效的在用视频模型目录，未更新本地目录。');
}

const models = await mapConcurrent(entries, 8, async (entry) => {
  const spec = await fetchJson(new URL(entry.source, docsRoot));
  if (spec.schemaVersion !== 1 || spec.publicModel !== entry.publicModel || !Array.isArray(spec.params)) {
    throw new Error(`官方规格与 manifest 不匹配：${entry.publicModel}`);
  }
  return {
    id: entry.id,
    publicModel: entry.publicModel,
    title: entry.title,
    summary: entry.summary,
    source: entry.source,
    lastReviewed: entry.lastReviewed,
    status: entry.status,
    spec,
  };
});

const content = [
  '// Generated by scripts/sync-cangyuan-video-model-catalog.mjs. Do not edit by hand.',
  "import type { CangyuanVideoModelCatalogEntry } from '@/packages/contracts/video-generation';",
  `export const CANGYUAN_VIDEO_MODEL_CATALOG = ${JSON.stringify(models, null, 2)} as const satisfies readonly CangyuanVideoModelCatalogEntry[];`,
  '',
].join('\n');
await writeFile(outputPath, content, 'utf8');
const incomplete = models.filter((model) => model.spec.params.length === 0).map((model) => model.publicModel);
console.log(`Updated ${models.length} current video model specs from ${manifestUrl}.`);
console.log(`Models without documented parameters: ${incomplete.length}${incomplete.length ? ` (${incomplete.join(', ')})` : ''}.`);
